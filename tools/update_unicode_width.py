"""Generate terminal width ranges from the pinned Unicode Character Database."""
from pathlib import Path
from urllib.request import urlopen
import hashlib

VERSION = '17.0.0'
BASE = f'https://www.unicode.org/Public/{VERSION}/ucd/'
ROOT = Path(__file__).resolve().parent.parent


def read_data(path):
    url = BASE + path
    with urlopen(url, timeout=30) as response:
        data = response.read()
    return url, data.decode('utf-8'), hashlib.sha256(data).hexdigest()


def codepoints(text, properties):
    result = set()
    for line in text.splitlines():
        record = line.split('#', 1)[0].strip()
        if not record:
            continue
        span, prop = (field.strip() for field in record.split(';'))
        if prop not in properties:
            continue
        ends = span.split('..')
        first, last = int(ends[0], 16), int(ends[-1], 16)
        result.update(range(first, last + 1))
    return result


def ranges(points):
    first = last = None
    for point in sorted(points):
        if last is not None and point == last + 1:
            last = point
            continue
        if last is not None:
            yield first, last
        first = last = point
    if last is not None:
        yield first, last


def main():
    categories = read_data('extracted/DerivedGeneralCategory.txt')
    widths = read_data('EastAsianWidth.txt')
    zero = codepoints(categories[1], {'Mn', 'Me', 'Cf'})
    # Soft hyphen occupies a cell; Hangul medial and final jamo combine.
    zero.discard(0x00AD)
    zero.update(range(0x1160, 0x1200))
    zero.update(range(0xD7B0, 0xD800))
    wide = codepoints(widths[1], {'W', 'F'})
    lines = [
        '// Generated by tools/update_unicode_width.py. Do not edit.',
        f'// Unicode {VERSION}; see LICENSE-UNICODE for the data license.',
    ]
    for url, _, checksum in (categories, widths):
        lines.extend([f'// Source: {url}', f'// SHA-256: {checksum}'])
    for name, points in (('zero_width', zero), ('wide', wide)):
        lines.extend(['', f'pub const {name} = [_][2]u21{{'])
        lines.extend(f'    .{{ 0x{first:x}, 0x{last:x} }},' for first, last in ranges(points))
        lines.append('};')
    (ROOT / 'src' / 'unicode_width_tables.zig').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
